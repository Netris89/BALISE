namespace Balise.DTO;

/// <summary>
/// A simple 2D coordinate used to describe polygon points and point-of-interest locations in import files.
/// </summary>
public class PointDto
{
    /// <summary>
    /// The X coordinate.
    /// </summary>
    public double X { get; set; }

    /// <summary>
    /// The Y coordinate.
    /// </summary>
    public double Y { get; set; }
}
